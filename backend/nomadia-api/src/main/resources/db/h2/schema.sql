-- NomadIA · Esquema para el perfil h2 (demostración y pruebas)
-- Réplica de nomadia_core tras los scripts 01 (DDL) y 02 (ALTER) del proyecto.
-- Diferencias con PostgreSQL: sin columnas PostGIS (GEOGRAPHY) y sin el disparador
-- trg_verifica_presupuesto; la Ley de Rigidez Financiera la aplica RigidezFinancieraService.
-- =============================================================
DROP SCHEMA IF EXISTS nomadia_core CASCADE;
CREATE SCHEMA nomadia_core;

CREATE TABLE nomadia_core.usuario (
    id_usuario        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres           VARCHAR(80)  NOT NULL,
    apellidos         VARCHAR(80)  NOT NULL,
    cedula            VARCHAR(20)  NOT NULL,
    fecha_nacimiento  DATE         NOT NULL,
    correo            VARCHAR(150) NOT NULL,
    contrasena        VARCHAR(255) NOT NULL,
    telefono          VARCHAR(15),
    creado_en         TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_usuario_cedula UNIQUE (cedula),
    CONSTRAINT uq_usuario_correo UNIQUE (correo)
);

CREATE TABLE nomadia_core.destino (
    id_destino  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(120) NOT NULL,
    ciudad      VARCHAR(120) NOT NULL,
    pais        VARCHAR(80)  NOT NULL,
    CONSTRAINT uq_destino UNIQUE (nombre, ciudad, pais)
);

CREATE TABLE nomadia_core.viaje (
    id_viaje      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio  DATE           NOT NULL,
    fecha_fin     DATE           NOT NULL,
    presupuesto   NUMERIC(15,2)  DEFAULT 0 NOT NULL,
    estado        VARCHAR(20)    DEFAULT 'activo' NOT NULL,
    moneda        CHAR(3)        DEFAULT 'COP' NOT NULL,
    id_usuario    BIGINT         NOT NULL,
    id_destino    BIGINT         NOT NULL,
    CONSTRAINT fk_viaje_usuario FOREIGN KEY (id_usuario)
        REFERENCES nomadia_core.usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_viaje_destino FOREIGN KEY (id_destino)
        REFERENCES nomadia_core.destino (id_destino) ON DELETE RESTRICT,
    CONSTRAINT chk_fechas       CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT chk_presupuesto  CHECK (presupuesto >= 0),
    CONSTRAINT chk_estado       CHECK (estado IN ('activo', 'finalizado', 'cancelado')),
    CONSTRAINT chk_viaje_moneda CHECK (moneda IN ('COP', 'USD'))
);

CREATE TABLE nomadia_core.itinerario (
    id_itinerario  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha          DATE         NOT NULL,
    descripcion    VARCHAR(255),
    orden          INTEGER      DEFAULT 1 NOT NULL,
    id_viaje       BIGINT       NOT NULL,
    CONSTRAINT fk_itin_viaje FOREIGN KEY (id_viaje)
        REFERENCES nomadia_core.viaje (id_viaje) ON DELETE CASCADE,
    CONSTRAINT chk_orden CHECK (orden > 0),
    CONSTRAINT uq_itinerario_orden UNIQUE (id_viaje, orden)
);

CREATE TABLE nomadia_core.actividad (
    id_actividad   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(120)   NOT NULL,
    descripcion    VARCHAR(500),
    direccion      VARCHAR(150),
    costo          NUMERIC(15,2)  DEFAULT 0 NOT NULL,
    id_itinerario  BIGINT         NOT NULL,
    CONSTRAINT fk_act_itin FOREIGN KEY (id_itinerario)
        REFERENCES nomadia_core.itinerario (id_itinerario) ON DELETE CASCADE,
    CONSTRAINT chk_costo CHECK (costo >= 0)
);

CREATE TABLE nomadia_core.gasto (
    id_gasto   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concepto   VARCHAR(150)   NOT NULL,
    monto      NUMERIC(15,2)  NOT NULL,
    fecha      DATE           DEFAULT CURRENT_DATE NOT NULL,
    categoria  VARCHAR(40)    DEFAULT 'general' NOT NULL,
    id_viaje   BIGINT         NOT NULL,
    CONSTRAINT fk_gasto_viaje FOREIGN KEY (id_viaje)
        REFERENCES nomadia_core.viaje (id_viaje) ON DELETE CASCADE,
    CONSTRAINT chk_monto CHECK (monto > 0),
    CONSTRAINT chk_gasto_categoria CHECK (categoria IN
        ('general', 'alojamiento', 'transporte', 'comida', 'ocio', 'compras'))
);
